"""Repair text references and add package redirects after the ChopIt content move.

Run from the project root with the Python bundled with Unreal Engine. The old
package list comes from HEAD so the mapping can be audited against the move.
"""

from collections import defaultdict
from pathlib import Path, PurePosixPath
import subprocess


ROOT = Path(__file__).resolve().parents[1]
OLD_ROOT = "Content/ChopIt/"
NEW_ROOT = "Content/NewChopIt/"
REDIRECT_MARKER = "; Generated by Tools/repair_content_relocation.py"
EXTENSIONS = {".cpp", ".h", ".ini", ".py"}


def package_name(path):
    return "/Game/" + path[len("Content/") :].rsplit(".", 1)[0]


old_assets = [
    path
    for path in subprocess.check_output(
        ["git", "ls-tree", "-r", "HEAD", "--name-only", OLD_ROOT],
        cwd=ROOT,
        text=True,
    ).splitlines()
    if PurePosixPath(path).suffix in {".uasset", ".umap"}
]
if not old_assets:
    raise RuntimeError(
        "HEAD no longer contains Content/ChopIt assets; refusing to rewrite redirects"
    )
new_assets = [
    path.relative_to(ROOT).as_posix()
    for path in (ROOT / NEW_ROOT).rglob("*")
    if path.suffix in {".uasset", ".umap"}
]
by_filename = defaultdict(list)
for path in new_assets:
    by_filename[PurePosixPath(path).name].append(path)

mapping = {}
missing = []
for old in old_assets:
    options = by_filename[PurePosixPath(old).name]
    if old == "Content/ChopIt/Art/Models/Slash/M_AxeSlash.uasset":
        options = ["Content/NewChopIt/Art/Models/Slash/M_AxeSlash.uasset"]
    elif old == "Content/ChopIt/Presentation/VFX/Materials/M_AxeSlash.uasset":
        options = ["Content/NewChopIt/Art/Materials/Slash/M_AxeSlash.uasset"]
    elif len(options) > 1 and old.startswith("Content/ChopIt/Art/Character/"):
        # Character imports have duplicate names in Imported, Updated, and the
        # parent directory. Their old relative suffix remains unchanged.
        suffix = old.removeprefix("Content/ChopIt/Art/Character/")
        options = [
            candidate
            for candidate in options
            if candidate.endswith("/Art/Models/Character/" + suffix)
        ]
    if len(options) != 1:
        missing.append((old, options))
        continue
    mapping[package_name(old)] = package_name(options[0])

# These paths are constructed at runtime or name destination folders, so there
# is no complete asset path for the package lookup above to replace.
directory_mapping = {
    "/Game/ChopIt/World/Blockout/Materials": "/Game/NewChopIt/Art/Blockout/Materials",
    "/Game/ChopIt/World/Generated": "/Game/NewChopIt/Terrain/Generated",
    "/Game/ChopIt/World/Maps": "/Game/NewChopIt/Maps",
    "/Game/ChopIt/Developer/Terrain": "/Game/NewChopIt/Terrain",
    "/Game/ChopIt/Art/Character": "/Game/NewChopIt/Art/Models/Character",
    "/Game/ChopIt/Art/Sticks": "/Game/NewChopIt/Art/Textures/Sticks",
    "/Game/ChopIt/Art/UI": "/Game/NewChopIt/Art/Textures/UI",
    "/Game/ChopIt/UI/Audio": "/Game/NewChopIt/Audio/UI",
    "/Game/ChopIt/UI": "/Game/NewChopIt/Art/UI",
    "/Game/ChopIt/Items/Mandrake": "/Game/NewChopIt/Art/Models/Mandrake",
    "/Game/ChopIt/Items/Chest": "/Game/NewChopIt/Art/Models/Chest",
    "/Game/ChopIt/Items": "/Game/NewChopIt/Data/Items",
    "/Game/ChopIt/Combat/Weapons": "/Game/NewChopIt/Data/Combat/Weapons",
    "/Game/ChopIt/Economy/Days": "/Game/NewChopIt/Data/Days",
    "/Game/ChopIt/Dialogue": "/Game/NewChopIt/Data/Dialogue",
    "/Game/ChopIt/Pacts": "/Game/NewChopIt/Data/Pacts",
    "/Game/ChopIt/Progression/Upgrades": "/Game/NewChopIt/Data/Progression/Upgrades",
    "/Game/ChopIt/Phone/Bargains": "/Game/NewChopIt/Data/Phone",
    "/Game/ChopIt/Phone": "/Game/NewChopIt/Art/Models/Phone",
    "/Game/ChopIt/Dialogue/Portraits": "/Game/NewChopIt/Art/Textures/Portraits",
    "/Game/ChopIt/Presentation/VFX/Meshes": "/Game/NewChopIt/Art/Models/Slash",
    "/Game/ChopIt/Presentation/VFX/Materials": "/Game/NewChopIt/Art/Materials/Slash",
    "/Game/ChopIt/Presentation/VFX/Textures": "/Game/NewChopIt/Art/Textures/Slash",
    "/Game/ChopIt/Presentation/VFX/Niagara": "/Game/NewChopIt/Art/FX",
    "/Game/ChopIt/Art/Models/Trees/New": "/Game/NewChopIt/Art/Models/Trees/New",
    "/Game/ChopIt/Art/Models/SetPieces": "/Game/NewChopIt/Art/Models/SetPieces",
    "/Game/ChopIt/Art/Materials": "/Game/NewChopIt/Art/Materials",
}

if missing:
    print("Assets with no unambiguous destination:")
    for old, options in missing:
        print(" ", old, "=>", options)

for directory in ("Source", "Config", "Scripts", "Tools"):
    for file in (ROOT / directory).rglob("*"):
        if file.suffix not in EXTENSIONS or file in {Path(__file__), ROOT / "Scripts/VerifyContentRelocation.py"}:
            continue
        original = file.read_text(encoding="utf-8-sig")
        updated = original.split(REDIRECT_MARKER)[0].rstrip() + "\n" if file == ROOT / "Config/DefaultEngine.ini" else original
        for old, new in sorted(mapping.items(), key=lambda pair: -len(pair[0])):
            updated = updated.replace(old, new)
        for old, new in sorted(directory_mapping.items(), key=lambda pair: -len(pair[0])):
            updated = updated.replace(old, new)
        if updated != original:
            file.write_text(updated, encoding="utf-8", newline="\n")
            print("Updated", file.relative_to(ROOT))

engine_config = ROOT / "Config/DefaultEngine.ini"
config = engine_config.read_text(encoding="utf-8-sig")
config = config.split(REDIRECT_MARKER)[0].rstrip() + "\n\n"
lines = [REDIRECT_MARKER, "[CoreRedirects]"]
for old, new in sorted(mapping.items()):
    lines.append(f'+PackageRedirects=(OldName="{old}",NewName="{new}")')
engine_config.write_text(config + "\n".join(lines) + "\n", encoding="utf-8", newline="\n")
print(f"Mapped {len(mapping)} packages; {len(missing)} need manual review.")
